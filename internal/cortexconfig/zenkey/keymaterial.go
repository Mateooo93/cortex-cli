package zenkey

import (
	"crypto/sha256"
)

// deriveKey assembles obfuscated seed material into the AES-256 key used
// to decrypt the bundled OpenCode Zen API credential.
func deriveKey() []byte {
	seed := make([]byte, 0, len(partA)+len(partB)+len(partC)+len(partD))
	seed = append(seed, partA...)
	seed = append(seed, partB...)
	seed = append(seed, partC...)
	seed = append(seed, partD...)
	sum := sha256.Sum256(seed)
	return sum[:]
}

var partA = []byte{
	0x63, 0x6f, 0x72, 0x74, 0x65, 0x78, 0x2d, 0x7a,
	0x65, 0x6e, 0x2d, 0x76, 0x31, 0x3a, 0x4d, 0x61,
}

var partB = []byte{
	0x74, 0x65, 0x6f, 0x39, 0x33, 0x3a, 0x6f, 0x70,
	0x65, 0x6e, 0x63, 0x6f, 0x64, 0x65, 0x2d, 0x7a,
}

var partC = []byte{
	0x65, 0x6e, 0x3a, 0x62, 0x75, 0x69, 0x6c, 0x74,
	0x69, 0x6e, 0x3a, 0x6d, 0x69, 0x6d, 0x6f, 0x2d,
}

var partD = []byte{
	0x76, 0x32, 0x2e, 0x35, 0x2d, 0x66, 0x72, 0x65,
	0x65, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
}
